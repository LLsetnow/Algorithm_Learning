    int res = 0;                // 方案数
    vector<vector<int>> paths;  // 方案集合
    vector<int> path;           // 方案

    // target = n - 当前路径之和; index为素数表的索引
    function<void(int, int)> backrack = [&](int target, int index){
        // 成功回溯：找到一个有效方案
        if(target == 0){
            paths.push_back(path);
            res++;
            return;
        }
        // 遍历所有可能的素数（从index开始，避免重复）
        for(int i = index; i < 168 && sushu[i] <= target; i++){
            path.push_back(sushu[i]);  // 选择当前素数
            backrack(target - sushu[i], i);  // 递归，传入i确保可以重复使用当前素数
            path.pop_back();  // 撤销选择
        }
    };

    backrack(n, 0);

